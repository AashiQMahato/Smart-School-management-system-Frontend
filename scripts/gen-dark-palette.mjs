/**
 * Generates src/styles/dark-palette.css from Tailwind's default palette.
 *
 * Tailwind v4 utilities read --color-* variables at runtime, so overriding
 * them under [data-theme="dark"] re-themes every page without editing it:
 * light tints (50-300) become dark tints of the same hue, dark shades
 * (700-950, mostly text) become light, and 400-600 stay as accents.
 *
 * Run: npm run gen:dark-palette
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const themePath = path.join(
  path.dirname(require.resolve("tailwindcss/package.json")),
  "theme.css",
);
const theme = readFileSync(themePath, "utf8");

const value = {};
for (const [, hue, shade, v] of theme.matchAll(
  /--color-([a-z]+)-(\d+):\s*([^;]+);/g,
)) {
  value[`${hue}-${shade}`] ??= v.trim();
}

const CHROMA = [
  "red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal",
  "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose",
];
const NEUTRALS = ["slate", "gray", "zinc", "neutral", "stone"];
const NEUTRAL_RAMP = {
  50: "#131d30", 100: "#18233a", 200: "#22304a", 300: "#2e3f5c",
  400: "#5b6b85", 500: "#8b99b0", 600: "#a9b5c7", 700: "#c3cdda",
  800: "#dbe2ec", 900: "#eef2f7", 950: "#f8fafc",
};
const DARK_BASE = "#0f1729";
const TINT_MIX = { 50: 12, 100: 18, 200: 28, 300: 42 };
const LIGHTEN_FROM = { 700: 300, 800: 200, 900: 100, 950: 50 };

const lines = [
  "/* Generated by scripts/gen-dark-palette.mjs — do not edit by hand. */",
  "",
  '[data-theme="dark"] {',
];
for (const n of NEUTRALS)
  for (const [shade, v] of Object.entries(NEUTRAL_RAMP))
    lines.push(`  --color-${n}-${shade}: ${v};`);
for (const hue of CHROMA) {
  const accent = value[`${hue}-500`];
  for (const [shade, pct] of Object.entries(TINT_MIX))
    lines.push(
      `  --color-${hue}-${shade}: color-mix(in oklab, ${accent} ${pct}%, ${DARK_BASE});`,
    );
  for (const [shade, from] of Object.entries(LIGHTEN_FROM))
    lines.push(`  --color-${hue}-${shade}: ${value[`${hue}-${from}`]};`);
}
lines.push("}", "");

// Surfaces that stay dark in both themes (banners) were written against
// the light palette (light text on navy). Restore it inside them.
const ALWAYS_DARK = [
  ".ssd-hero",
  ".bg-\\[var\\(--ssd-hero\\)\\]",
  ".ssd-always-dark",
];
lines.push(
  "/* Always-dark surfaces keep the light-theme palette. */",
  `[data-theme="dark"] :is(${ALWAYS_DARK.join(", ")}) {`,
);
for (const n of [...NEUTRALS, ...CHROMA])
  for (const shade of Object.keys(NEUTRAL_RAMP))
    if (value[`${n}-${shade}`])
      lines.push(`  --color-${n}-${shade}: ${value[`${n}-${shade}`]};`);
lines.push("}", "");
lines.push(
  `[data-theme="dark"] :is(${ALWAYS_DARK.join(", ")}) .bg-white {`,
  "  background-color: #fff;",
  "}",
  "",
);

const out = new URL("../src/styles/dark-palette.css", import.meta.url);
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${lines.length} lines to src/styles/dark-palette.css`);
